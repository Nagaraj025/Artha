package com.subramanya.artha.data.mapper

import com.subramanya.artha.data.entity.TransactionEntity
import com.subramanya.artha.domain.model.Transaction

fun TransactionEntity.toDomain(peopleIds: List<String> = emptyList(), tagIds: List<String> = emptyList()): Transaction = Transaction(
    id = id,
    type = type,
    amount = amount,
    currency = currency,
    date = date,
    description = description,
    categoryId = categoryId,
    subCategoryId = subCategoryId,
    sourceType = sourceType,
    sourceId = sourceId,
    destinationType = destinationType,
    destinationId = destinationId,
    paymentApp = paymentApp,
    place = place,
    latitude = latitude,
    longitude = longitude,
    peopleIds = peopleIds,
    tagIds = tagIds,
    receiptUri = receiptUri,
    notes = notes,
    taxSection = taxSection,
    recurringRuleId = recurringRuleId,
    isSplit = isSplit,
    splitGroupId = splitGroupId,
    source = source,
    createdAt = createdAt,
    updatedAt = updatedAt,
    excludedFromExpenseTotal = excludedFromExpenseTotal,
)

